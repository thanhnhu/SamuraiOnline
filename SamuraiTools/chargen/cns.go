func BuildAttacks(src *Source) []AttackSpec {
	var out []AttackSpec
	for _, a := range attackStates {
		anim := src.Anim(a.name)
		if anim == nil {
			continue
		}
		hitElem := 0
		for i, f := range anim.Frames {
			if len(f.Attack) > 0 {
				hitElem = i + 1
				break
			}
		}
		if hitElem == 0 {
			// No active frame means the table has no attack box; skip rather
			// than emit a move that can never connect.
			continue
		}
		// Unlike the collision boxes, damage is animation-scoped in the source:
		// every PushBack overwrites it, so the last call is what the original
		// engine actually used. Reading it per frame would pick up values that
		// were only ever dead data, such as the punch's stray 212.
		damage := anim.Frames[len(anim.Frames)-1].Damage
		if damage <= 0 || damage > 120 {
			damage = 10
		}
		spec := AttackSpec{
			State: a.state, Anim: a.anim, Name: a.name, Type: a.kind,
			Damage: damage, HitElem: hitElem, Height: a.height,
			Command: a.button, IsSlash: a.slash,
		}
		spec.DisarmedAnim, spec.HasDisarmed = DisarmedFor(src, a.anim)
		out = append(out, spec)
	}
	return out
}

