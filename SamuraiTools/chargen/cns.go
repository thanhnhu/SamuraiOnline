// Generates the character definition files around the converted animations.
//
// Reactive states (being hit, falling, guarding, dizzy) are left to Ikemen's
// common states. What is written here is the part Samurai Shodown does
// differently from a stock MUGEN character:
//
//   - four attack buttons rather than six, with the heavy slash also on both
//     light slash buttons at once
//   - a POW gauge that fills from damage taken instead of damage dealt
//   - a disarmed state that swaps in the weaponless animation set and cuts
//     damage until the sword is picked back up

// Buttons, in MUGEN terms: x/y/z are punches (here, slashes) and a/b/c kicks.
// The two families mirror each other: light, medium, and a heavy that also
// comes out of the two lighter buttons pressed together.
const (
	btnLightSlash  = "x"
	btnMediumSlash = "y"
	btnHeavySlash  = "z"
	btnLightKick   = "a"
	btnMediumKick  = "b"
	btnHeavyKick   = "c"
	btnRearm       = "d"
)

// varDisarmed is set to 1 once the sword has been knocked away.
const varDisarmed = 0

// powRageStart is where the gauge counts as full, on Ikemen's 0..3000 scale.
const powRageStart = 2500

type AttackSpec struct {
	State   int32
	Anim    int32
	Name    string
	Type    string // S, C or A
	Damage  int
	HitElem int    // 1-based AnimElem that first has an attack box
	Height  string // High or Low
	Command string
	// DisarmedAnim is the weaponless animation, when the source ships one.
	DisarmedAnim int32
	HasDisarmed  bool
	// IsSlash marks weapon attacks, which lose most of their damage once the
	// sword is gone.
	IsSlash bool
}

