package main

import (
	"fmt"
	"image"
	"os"
	"path/filepath"
	"strings"
)

// The original renders 320x224. Ikemen stages are conventionally authored in a
// 320x240 space, so the extra rows sit below the floor and stay off screen.
const (
	stageWidth  = 320
	stageHeight = 240
	// groundLine is where characters stand, measured from the top. The value
	// the original uses is not in the .BGR file, so this is a starting point to
	// tune per stage rather than a decoded constant.
	groundLine = 200
)

// Layer is one decoded background plane on its way into a stage.
type Layer struct {
	ID    uint16
	Image *image.NRGBA
}

// StageOptions carries the parts of a stage that the .BGR file does not
// describe. None of it is decoded, so all of it is a starting point.
type StageOptions struct {
	Name  string
	Music string // path relative to the engine root, empty for silence
	Delta float64
}

// WriteStage writes one Ikemen stage: an .sff holding the layers and a .def
// pointing at them.
func WriteStage(dir, base string, layers []Layer, opt StageOptions) error {
	if len(layers) == 0 {
		return fmt.Errorf("%s has no layers", base)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	sprites := make([]SffSprite, 0, len(layers))
	for i, l := range layers {
		sprites = append(sprites, SffSprite{
			Group:  0,
			Number: uint16(i),
			Img:    toRGBA(l.Image),
		})
	}
	if err := WriteSff(filepath.Join(dir, base+".sff"), sprites); err != nil {
		return err
	}

	def := buildDef(base, layers, opt)
	return os.WriteFile(filepath.Join(dir, base+".def"), []byte(def), 0o644)
}

func toRGBA(src *image.NRGBA) *image.RGBA {
	b := src.Bounds()
	dst := image.NewRGBA(b)
	for y := b.Min.Y; y < b.Max.Y; y++ {
		for x := b.Min.X; x < b.Max.X; x++ {
			dst.Set(x, y, src.At(x, y))
		}
	}
	return dst
}

func buildDef(base string, layers []Layer, opt StageOptions) string {
	var b strings.Builder
	name := opt.Name
	if name == "" {
		name = base
	}

	fmt.Fprintf(&b, "; Generated by stagegen from %s.BGR.\n", base)
	b.WriteString("; Do not edit by hand: regenerate instead. The layer art is\n")
	b.WriteString("; decoded from Samurai Shodown II, which SNK still sells, so\n")
	b.WriteString("; neither this file nor the .sff beside it belongs in git.\n\n")

	fmt.Fprintf(&b, "[Info]\nname = %q\ndisplayname = %q\nmugenversion = 1.1\nauthor = \"stagegen\"\n\n",
		name, name)

	b.WriteString("[Camera]\nstartx = 0\nstarty = 0\n")
	b.WriteString("boundleft = -150\nboundright = 150\nboundhigh = -22\nboundlow = 0\n")
	b.WriteString("verticalfollow = .2\nfloortension = 0\ntension = 60\n")
	b.WriteString("overdrawhigh = 0\noverdrawlow = 0\ncuthigh = 0\ncutlow = 0\n")
	b.WriteString("zoomout = 1\nzoomin = 1\n\n")

	b.WriteString("[PlayerInfo]\np1startx = -70\np1starty = 0\np1facing = 1\n")
	b.WriteString("p2startx = 70\np2starty = 0\np2facing = -1\n")
	b.WriteString("leftbound = -1000\nrightbound = 1000\n\n")

	b.WriteString("[Bound]\nscreenleft = 15\nscreenright = 15\n\n")

	fmt.Fprintf(&b, "[StageInfo]\nzoffset = %d\nautoturn = 1\nresetBG = 1\nlocalcoord = %d, %d\n\n",
		groundLine, stageWidth, stageHeight)

	b.WriteString("[Music]\n")
	if opt.Music != "" {
		fmt.Fprintf(&b, "bgmusic = %s\n", opt.Music)
		b.WriteString("bgmvolume = 100\n")
	} else {
		b.WriteString("; no music: stagegen found no .WAV for this stage\n")
	}
	b.WriteString("\n")

	fmt.Fprintf(&b, "[BGdef]\nspr = %s.sff\ndebugbg = 0\n\n", base)

	delta := opt.Delta
	if delta <= 0 {
		delta = 1
	}

	for i, l := range layers {
		bounds := l.Image.Bounds()
		// Anchor each layer to the bottom of the play area. Where the original
		// actually put them is held in a stage table that is not decoded yet,
		// so this lines the art up with the floor and leaves the rest to
		// whoever tunes the stage.
		y := stageHeight - bounds.Dy()
		if y > 0 {
			y = 0
		}
		fmt.Fprintf(&b, "[BG layer %d id %d]\ntype = normal\nspriteno = 0, %d\nlayerno = 0\n",
			i, l.ID, i)
		fmt.Fprintf(&b, "start = 0, %d\ndelta = %g, %g\ntile = 1, 0\n\n", y, delta, delta)
	}

	return b.String()
}
